// Generates src/styles/icons.css: the subset of @mdi/font rules the app uses.
// Run after adding an icon: npm run icons
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ICONS_CSS = path.join(ROOT, 'src/styles/icons.css');

// Icons Vuetify components render through aliases ($close, $menu, ...), not visible in src
export const VUETIFY_DEFAULT_ICONS = [
  'mdi-checkbox-marked',
  'mdi-checkbox-blank-outline',
  'mdi-minus-box',
  'mdi-circle',
  'mdi-arrow-up',
  'mdi-arrow-down',
  'mdi-chevron-down',
  'mdi-chevron-up',
  'mdi-check',
  'mdi-close-circle',
  'mdi-close',
  'mdi-check-circle',
  'mdi-information',
  'mdi-alert-circle',
  'mdi-chevron-left',
  'mdi-chevron-right',
  'mdi-radiobox-marked',
  'mdi-radiobox-blank',
  'mdi-pencil',
  'mdi-star-outline',
  'mdi-star',
  'mdi-star-half-full',
  'mdi-cached',
  'mdi-page-first',
  'mdi-page-last',
  'mdi-unfold-more-horizontal',
  'mdi-paperclip',
  'mdi-plus',
  'mdi-minus',
  'mdi-calendar',
  'mdi-eye',
  'mdi-eye-off',
  'mdi-menu-down',
  'mdi-menu-up',
  'mdi-menu'
];

const ICON_ALIASES = {
  'mdi-sparkles': 'mdi-creation'
};

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return /\.(vue|js|ts)$/.test(entry.name) ? [full] : [];
  });
}

export function collectUsedIcons() {
  const used = new Set(VUETIFY_DEFAULT_ICONS);
  for (const file of walk(path.join(ROOT, 'src'))) {
    const content = fs.readFileSync(file, 'utf8');
    for (const m of content.match(/mdi-[a-z0-9-]+/g) || []) used.add(m);
  }
  return used;
}

export function definedIcons(css = fs.readFileSync(ICONS_CSS, 'utf8')) {
  return new Set([...css.matchAll(/\.(mdi-[a-z0-9-]+)::before/g)].map(m => m[1]));
}

function generate() {
  const fullCss = fs.readFileSync(path.join(ROOT, 'node_modules/@mdi/font/css/materialdesignicons.css'), 'utf8');

  const iconRules = [];
  for (const icon of collectUsedIcons()) {
    const targetIcon = ICON_ALIASES[icon] || icon;
    const regex = new RegExp(`\\.${targetIcon}::before\\s*\\{[^}]*\\}`, 'g');
    const match = fullCss.match(regex);
    if (match) {
      if (targetIcon !== icon) {
        iconRules.push(match[0].replace(new RegExp(`\\.${targetIcon}::before`), `.${icon}::before`));
      }
      iconRules.push(match[0]);
    } else {
      console.warn(`Icon ${icon} not found in materialdesignicons.css`);
    }
  }

  const optimizedCss = `/* Material Design Icons - Optimized subset for MyMeds (WOFF2 only) */
/* Generated by scripts/generate-icon-css.mjs (npm run icons), do not edit by hand */
@font-face {
  font-family: "Material Design Icons";
  src: url("@mdi/font/fonts/materialdesignicons-webfont.woff2?v=7.4.47") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: swap;
}

.mdi:before,
.mdi-set {
  display: inline-block;
  font: normal normal normal 24px/1 "Material Design Icons";
  font-size: inherit;
  text-rendering: auto;
  line-height: inherit;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${iconRules.join('\n')}
`;

  fs.writeFileSync(ICONS_CSS, optimizedCss, 'utf8');
  console.log(`Generated src/styles/icons.css with ${iconRules.length} icons (Size: ${(optimizedCss.length / 1024).toFixed(1)} kB)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generate();
}
